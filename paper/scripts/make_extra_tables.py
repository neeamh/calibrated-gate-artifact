"""Mechanism and sensitivity tables, plus failing-dimension counts, from saved evidence."""
import json, pathlib, pandas as pd
_ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = _ROOT / 'paper' / 'generated'
DATA = _ROOT / 'results' / 'main_v5' / 'analysis_tables'
PROFILES = _ROOT / 'results' / 'main_v5' / 'profiles' / 'jobs'
X = json.load(open(HERE / 'extra_numbers.json'))
mech = X['mechanism']
status = json.load(open(HERE / 'mechanism_status.json'))
def fmt(v):
    return '0' if v == 0 else ('$<$0.01' if v < .005 else f'{v:.2f}')
def cell(k, d):
    s, n = status[k][d], status[k]['n']
    text = f'{fmt(mech[k][d])}\\,({s}/{n})'
    return f'\\miss{{{text}}}' if s < n / 2 else text
rows = [('Honest audit runs', 'honest|audit'), ('Positive controls', 'positive|control'), None,
        ('Copied rows, 0.1\\%', 'exact_copy|0.001'), ('Copied rows, 5\\%', 'exact_copy|0.05'),
        ('Shuffled predictor, 50\\%', 'feature_shuffle|0.5'), ('Shuffled predictor, 90\\%', 'feature_shuffle|0.9'),
        ('Missing values, 5\\%', 'mcar|0.05'), ('Missing values, 30\\%', 'mcar|0.3'),
        ('Suppressed subgroup, 10\\%', 'subgroup_suppression|0.1'), ('Suppressed subgroup, 90\\%', 'subgroup_suppression|0.9'),
        ('Copy control', 'copy|all')]
lines = [r'\midrule' if r is None else f"{r[0]} & " + ' & '.join(cell(r[1], d) for d in ('fidelity', 'utility', 'privacy')) + r' \\' for r in rows]
(HERE / 'table_mechanism.tex').write_text('\n'.join(lines) + '\n\\bottomrule\n')
sens = X['sensitivity']
lines = []
for T in ('1.0', '2.0', '3.0', '5.0', '10.0'):
    r = sens[T]
    star = '$^\\ast$' if T == '3.0' else ''
    lines.append(f"{float(T):g}{star} & {X['gate']['bad']} & {r['Harmonic']['bad']} & {r['Geometric']['bad']} & {r['Mean']['bad']} \\\\")
(HERE / 'table_sensitivity.tex').write_text('\n'.join(lines) + '\n\\bottomrule\n')
# Failing gating dimensions per flawed table rejected by the gate.
d = pd.read_csv(DATA / 'dimension_status.csv')
s = d[(d.variant == 'calibrated') & (d.alpha == .05)]
inj = s[(s.kind == 'injection') & (s.baseline_kind == 'positive') & (s.dose > 0)]
cp = s[(s.kind == 'control') & (s.control == 'copy')]
prim = pd.concat([inj, cp]); assert len(prim) == 39
nfail = (prim[['fidelity', 'utility', 'privacy']] == 'Fail').sum(axis=1)
rej = prim[prim.gate != 'Pass']
one, two = int((nfail[rej.index] == 1).sum()), int((nfail[rej.index] == 2).sum())
hon_range = [min(r[j]['honest'] for r in sens.values() for j in r), max(r[j]['honest'] for r in sens.values() for j in r)]
mac = [f'\\newcommand{{\\NRejected}}{{{len(rej)}}}', f'\\newcommand{{\\NOneDim}}{{{one}}}', f'\\newcommand{{\\NTwoDim}}{{{two}}}',
       f"\\newcommand{{\\SensMeanMin}}{{{min(r['Mean']['bad'] for r in sens.values())}}}",
       f"\\newcommand{{\\SensMeanMax}}{{{max(r['Mean']['bad'] for r in sens.values())}}}",
       f"\\newcommand{{\\SensHarmMin}}{{{min(r['Harmonic']['bad'] for r in sens.values())}}}",
       f"\\newcommand{{\\SensHonMin}}{{{hon_range[0]}}}", f"\\newcommand{{\\SensHonMax}}{{{hon_range[1]}}}"]
(HERE / 'numbers_extra.tex').write_text('% Generated by make_extra_tables.py\n' + '\n'.join(mac) + '\n')
print('\n'.join(mac)); print(open(HERE / 'table_mechanism.tex').read()); print(open(HERE / 'table_sensitivity.tex').read())
assert len(rej) == 30 and X['gate']['bad'] == 9
