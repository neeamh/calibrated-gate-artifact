"""Macros and the combined sensitivity table from reanalysis.json and extra_numbers.json."""
import json, pathlib
import numpy as np
_ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = _ROOT / 'paper' / 'generated'
DATA = _ROOT / 'results' / 'main_v5' / 'analysis_tables'
PROFILES = _ROOT / 'results' / 'main_v5' / 'profiles' / 'jobs'
R = json.load(open(HERE / 'reanalysis.json')); X = json.load(open(HERE / 'extra_numbers.json'))
mac = []
def m(name, value):
    assert name.isalpha(), name
    mac.append(f'\\newcommand{{\\{name}}}{{{value}}}')
aw = {'0.025': 'A', '0.05': 'B', '0.1': 'C'}
jw = {'Gate': 'Gate', 'Mean': 'Mean', 'Geometric': 'Geo', 'Harmonic': 'Harm', 'SDMetrics': 'SDM'}
for a, al in aw.items():
    for j, row in R['percentile_mapping'][a].items():
        m(f'Pct{jw[j]}{al}', row['bad']); m(f'PctHon{jw[j]}{al}', row['honest'])
    for j, row in R['without_proximity']['matched'][a].items():
        m(f'NP{jw[j]}{al}', row['bad']); m(f'NPHon{jw[j]}{al}', row['honest'])
    for d, v in R['without_proximity']['audit'][a].items():
        m(f'NPAudit{d.capitalize()}{al}', v)
    for d, v in R['calibration_diagnostics']['rates'][a].items():
        m(f'Diag{d.capitalize()}{al}', f"{100*v:.1f}\\%" if d == 'nominal' else v)
gc = R['gaussian_copula']
m('GCInjected', gc['injected']['Gate']['n']); m('GCBaseline', gc['dose0_baseline']['Gate']['n'])
assert all(gc[s][j]['accepted'] == 0 for s in gc for j in jw)
m('GCFailPriv', gc['injected']['failing_dimensions']['privacy'])
m('GCFailFid', gc['injected']['failing_dimensions']['fidelity']); m('GCFailUtil', gc['injected']['failing_dimensions']['utility'])
pv = np.array(R['calibration_diagnostics']['audit_gate_pvalues'])
for t, name in [(.05, 'Five'), (.1, 'Ten'), (.2, 'Twenty')]:
    m(f'PvBelow{name}', int((pv <= t).sum()))
changed = [k for k, v in R['without_proximity']['controls_generators'].items() if v['privacy_before'] != v['privacy_after']]
m('NPPrivFlips', len(changed)); assert all(('DPAIM' in k or 'TVAE' in k) for k in changed)
assert not R['without_proximity']['primary_changes']
(HERE / 'numbers_reanalysis.tex').write_text('% Generated by make_reanalysis_tables.py; do not edit by hand.\n' + '\n'.join(mac) + '\n')

# Combined sensitivity table: flawed tables accepted (of 39), honest audit runs accepted (of 50) in parentheses.
cell = lambda b, h: f'{b}\\,({h})'
lines = [r'\multicolumn{5}{@{}l}{\textit{Exponential mapping, temperature $t$}} \\']
for t in ('1.0', '2.0', '3.0', '5.0', '10.0'):
    s = X['sensitivity'][t]; label = f"$t={float(t):g}$" + ('$^\\ast$' if t == '3.0' else '')
    lines.append(f"{label} & {cell(X['gate']['bad'], X['gate']['honest'])} & " +
                 ' & '.join(cell(s[j]['bad'], s[j]['honest']) for j in ('Harmonic', 'Geometric', 'Mean')) + r' \\')
lines.append(r'\addlinespace[2pt]')
lines.append(r'\multicolumn{5}{@{}l}{\textit{Empirical percentile mapping}} \\')
for a, label in (('0.025', r'$\alpha=0.025$'), ('0.05', r'$\alpha=0.05$'), ('0.1', r'$\alpha=0.10$')):
    s = R['percentile_mapping'][a]
    lines.append(f'{label} & ' + ' & '.join(cell(s[j]['bad'], s[j]['honest']) for j in ('Gate', 'Harmonic', 'Geometric', 'Mean')) + r' \\')
lines.append(r'\addlinespace[2pt]')
lines.append(r'\multicolumn{5}{@{}l}{\textit{Without the closer-than-real privacy signal}} \\')
for a, label in (('0.025', r'$\alpha=0.025$'), ('0.05', r'$\alpha=0.05$'), ('0.1', r'$\alpha=0.10$')):
    s = R['without_proximity']['matched'][a]
    lines.append(f'{label} & ' + ' & '.join(cell(s[j]['bad'], s[j]['honest']) for j in ('Gate', 'Harmonic', 'Geometric', 'Mean')) + r' \\')
(HERE / 'table_sensitivity_all.tex').write_text('\n'.join(lines) + '\n\\bottomrule\n')
print(open(HERE / 'numbers_reanalysis.tex').read()); print(open(HERE / 'table_sensitivity_all.tex').read())
